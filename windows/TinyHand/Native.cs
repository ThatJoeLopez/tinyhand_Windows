    public static void SetExStyle(IntPtr hwnd, long add, long remove = 0)
    {
        long style = GetWindowLongPtr(hwnd, GWL_EXSTYLE).ToInt64();
        long next = (style | add) & ~remove;
        if (next != style)
        {
            SetWindowLongPtr(hwnd, GWL_EXSTYLE, new IntPtr(next));
        }
    }

