    /// The monitor the point is on (physical pixels), with its work area and scale factor.
    public static (RECT bounds, RECT work, double scale, IntPtr handle) MonitorAt(POINT p)
    {
        IntPtr mon = MonitorFromPoint(p, MONITOR_DEFAULTTONEAREST);
        var info = new MONITORINFO { cbSize = Marshal.SizeOf<MONITORINFO>() };
        GetMonitorInfo(mon, ref info);
        double scale = 1;
        try
        {
            if (GetDpiForMonitor(mon, 0, out uint dx, out _) == 0 && dx > 0)
            {
                scale = dx / 96.0;
            }
        }
        catch (DllNotFoundException)
        {
        }
        catch (EntryPointNotFoundException)
        {
        }
        return (info.rcMonitor, info.rcWork, scale, mon);
    }
