    [StructLayout(LayoutKind.Sequential)]
    public struct POINT
    {
        public int X;
        public int Y;
    }

    [StructLayout(LayoutKind.Sequential)]
    public struct RECT
    {
        public int Left;
        public int Top;
        public int Right;
        public int Bottom;

        public int Width => Right - Left;
        public int Height => Bottom - Top;

        public bool Contains(POINT p) => p.X >= Left && p.X < Right && p.Y >= Top && p.Y < Bottom;

        public RECT Inflate(int dx, int dy) => new() { Left = Left - dx, Top = Top - dy, Right = Right + dx, Bottom = Bottom + dy };

        public override string ToString() => $"{Left},{Top} {Width}x{Height}";
    }

